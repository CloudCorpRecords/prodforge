const DESCRIPTIONS: Record<Stack, string> = {
  "mcp-server": "An MCP server: CLI + MCP in one bin, following the ProdForge fleet factory pattern.",
  "saas-web": "A web SaaS skeleton: health endpoint, env-driven port, no framework lock-in.",
  "api-service": "An API service skeleton: validated handlers with structured status results.",
  "cli-tool": "A CLI tool skeleton: pure argument parsing and command dispatch in one bin.",
  "ai-agent": "An AI agent skeleton: allowlisted tools and traceable plans, no SDK lock-in.",
};

export function scaffoldFiles(stack: Stack, name: string): Record<string, string> {
  const description = DESCRIPTIONS[stack];
  const files: Record<string, string> = {
    "package.json": packageJson(name, description, stack === "cli-tool" || stack === "mcp-server" ? name : undefined),
    "tsconfig.json": TS_CONFIG,
    ".gitignore": GITIGNORE,
    "README.md": readme(stack, name, description),
    "src/index.ts": SOURCES[stack](name),
    "test/index.test.ts": TESTS[stack].replaceAll("GENERATED_NAME", name),
  };
  if (stack === "mcp-server") {
    files["server.json"] = JSON.stringify(
      { name: `io.github.example/${name}`, version: "0.1.0", description, packages: [{ registryType: "npm", identifier: name }] },
      null,
      2,
    ) + "\n";
  }
  return files;
}

/** Write a scaffold into dir. Refuses to clobber a non-empty directory. */
export function initStack(stack: Stack, dir: string, name: string): string[] {
  if (existsSync(dir) && readdirSync(dir).length > 0) {
    throw new Error(`directory already exists and is not empty: ${dir}`);
  }
  mkdirSync(dir, { recursive: true });
  const files = scaffoldFiles(stack, name);
  const written: string[] = [];
  for (const [rel, content] of Object.entries(files)) {
    const target = join(dir, rel);
    mkdirSync(join(dir, rel.split("/").slice(0, -1).join("/")), { recursive: true });
    writeFileSync(target, content);
    written.push(rel);
  }
  return written;
}
