import { mkdirSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

export const STACKS = ["mcp-server", "saas-web", "api-service", "cli-tool", "ai-agent"] as const;
export type Stack = (typeof STACKS)[number];

export function isStack(value: string): value is Stack {
  return (STACKS as readonly string[]).includes(value);
}

const TS_CONFIG = JSON.stringify(
  {
    compilerOptions: {
      target: "ES2022",
      module: "NodeNext",
      moduleResolution: "NodeNext",
      outDir: "dist",
      strict: true,
      skipLibCheck: true,
    },
    include: ["src", "test"],
  },
  null,
  2,
) + "\n";

const GITIGNORE = "node_modules/\ndist/\n.env\n*.log\n";

function packageJson(name: string, description: string, binName?: string): string {
  const pkg: Record<string, unknown> = {
    name,
    version: "0.1.0",
    description,
    type: "module",
    scripts: { build: "tsc", test: "tsx --test test/*.test.ts" },
    devDependencies: { "@types/node": "^20", tsx: "^4", typescript: "^5" },
    engines: { node: ">=20" },
    license: "MIT",
  };
  if (binName) pkg.bin = { [binName]: "dist/index.js" };
  return JSON.stringify(pkg, null, 2) + "\n";
}

function readme(stack: Stack, name: string, description: string): string {
  return `# ${name}\n\n${description}\n\nStack: \`${stack}\` (generated by \`prodforge init ${stack} ${name}\`).\n\n## Develop\n\n\`\`\`sh\nnpm install\nnpm test\nnpm run build\n\`\`\`\n\n## Ship gates (before you tag)\n\n- [ ] Tests green, build clean\n- [ ] No secrets in the repo (run a secret scan before publishing)\n- [ ] Tag = release = published artifact, verified after publish\n`;
}

